def load_iiko():
    rows = []
    for e in json.load(open(IIKO)):
        sec = section(e)
        if not sec or e['lastDate'] < SINCE or not e['price']: continue
        rows.append({**e, 'display': display(e['name']), 'section': sec})
    return rows
